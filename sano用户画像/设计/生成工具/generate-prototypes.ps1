}

function Info($X, $Y, [string]$Label, [string]$Value, $ValueX = 118) {
    Text $X $Y $Label 12 '#64748B' 400
    Text ($X + $ValueX) $Y $Value 13 '#1E293B' 500
}

function ChartAxes($X, $Y, $W, $H, [string]$Unit = '$') {
    Line $X ($Y + $H) ($X + $W) ($Y + $H) '#CBD5E1'
    Line $X $Y $X ($Y + $H) '#CBD5E1'
    foreach ($p in @(0.25,0.5,0.75)) {
        $gy = $Y + $H * $p
        Line $X $gy ($X + $W) $gy '#EEF2F7' 1 '4 4'
    }
    Text ($X - 8) ($Y + 4) $Unit 11 '#94A3B8' 400 'end'
}

function MiniTable($X, $Y, $W, [string[]]$Headers, [object[]]$Rows, [int[]]$Widths, $RowHeight = 40) {
    Rect $X $Y $W 36 '#F8FAFC' 6
    $cx = $X
    for ($i=0; $i -lt $Headers.Count; $i++) {
        Text ($cx + 10) ($Y + 23) $Headers[$i] 12 '#64748B' 500
        $cx += $Widths[$i]
    }
    for ($r=0; $r -lt $Rows.Count; $r++) {
        $ry = $Y + 36 + $r * $RowHeight
        Line $X $ry ($X + $W) $ry '#EEF2F7'
        $cx = $X
        for ($i=0; $i -lt $Headers.Count; $i++) {
            Text ($cx + 10) ($ry + 25) ([string]$Rows[$r][$i]) 12 '#334155' 400
            $cx += $Widths[$i]
        }
    }
}

function RankBars($X, $Y, $W, [string[]]$Names, [double[]]$Values, $Color = '#C7D2FE', $Rows = 5) {
    $MaxValue = ($Values | Measure-Object -Maximum).Maximum
    $BarStart = $X + 118
    $BarMax = $W - 220
    for ($i=0; $i -lt [Math]::Min($Rows, $Names.Count); $i++) {
        $RowY = $Y + $i * 37
        Text $X ($RowY + 16) (('{0}. {1}' -f ($i + 1),$Names[$i])) 10 '#475569' 400
